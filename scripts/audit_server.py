from __future__ import annotations

import argparse
import os
import shutil
import subprocess
from pathlib import Path


def run(command: list[str]) -> str:
    if shutil.which(command[0]) is None:
        return f"NOT AVAILABLE: {command[0]}\n"
    result = subprocess.run(command, capture_output=True, text=True, timeout=120)
    output = result.stdout
    if result.stderr:
        output += f"\nSTDERR:\n{result.stderr}"
    return f"$ {' '.join(command)}\nexit={result.returncode}\n{output}".rstrip() + "\n"


def discover(roots: list[Path], max_depth: int = 4) -> list[Path]:
    terms = ("osworld", "qwen3", "qwen-32b", "qwen32b", "stateguard")
    found = set()
    for root in roots:
        if not root.exists():
            continue
        base_depth = len(root.parts)
        for current, dirs, _ in os.walk(root):
            path = Path(current)
            if len(path.parts) - base_depth >= max_depth:
                dirs[:] = []
            if any(term in path.name.lower() for term in terms):
                found.add(path)
    return sorted(found)


def main():
    parser = argparse.ArgumentParser(description="Collect the StateGuard server audit bundle")
    parser.add_argument("--output", default="artifacts/server2_audit")
    parser.add_argument("--roots", nargs="*", default=[str(Path.home()), "/data", "/mnt"])
    args = parser.parse_args()
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    bundles = {
        "hardware.txt": [["hostname"], ["lscpu"], ["free", "-h"]],
        "gpu.txt": [["nvidia-smi", "-L"], ["nvidia-smi"]],
        "docker.txt": [["docker", "--version"], ["docker", "ps", "-a"],
                       ["docker", "images"]],
        "kvm.txt": [["ls", "-l", "/dev/kvm"],
                    ["sh", "-c", "egrep -c '(vmx|svm)' /proc/cpuinfo"]],
        "disk.txt": [["df", "-h"]],
        "conda.txt": [["conda", "env", "list"]],
        "running_services.txt": [
            ["sh", "-c", "ps -ef | grep -E 'vllm|sglang|qwen|osworld' | grep -v grep"],
            ["ss", "-lntp"],
        ],
    }
    for name, commands in bundles.items():
        (output / name).write_text("\n".join(run(command) for command in commands),
                                   encoding="utf-8")

    assets = discover([Path(value).expanduser() for value in args.roots])
    images = run(["docker", "images", "--format", "{{.Repository}}:{{.Tag}} {{.ID}} {{.Size}}"])
    services = (output / "running_services.txt").read_text(encoding="utf-8")
    report = [
        "# Discovered assets", "",
        "Generated by `scripts/audit_server.py`; no credentials are collected.", "",
        "## Existing OSWorld paths", "",
        *[f"- `{path}`" for path in assets if "osworld" in str(path).lower()],
        "", "## Existing Qwen checkpoints/deployments", "",
        *[f"- `{path}`" for path in assets if "qwen" in str(path).lower()],
        "", "## Existing StateGuard paths", "",
        *[f"- `{path}`" for path in assets if "stateguard" in str(path).lower()],
        "", "## Existing Docker images", "", "```text", images.rstrip(), "```",
        "", "## Existing model endpoints and multimodal APIs", "", "```text",
        services.rstrip(), "```", "",
        "Exact model identity and multimodal behavior must be verified separately with ",
        "`scripts/test_model_api.py`; a listening port alone is not a reuse PASS.",
    ]
    (output / "discovered_assets.md").write_text("\n".join(report), encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
